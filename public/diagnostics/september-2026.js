  function resultEvidence(primary, secondary, profileKey) {
    const baseline = ["q1", "q2", "q4"].map(selectedAnswer).filter(Boolean);
    const primaryAnswers = primary.questionIds.map(selectedAnswer).filter(Boolean);
    const secondaryAnswers = secondary.questionIds.map(selectedAnswer).filter(Boolean);
    const expectedRevenue = value("q3_expected");
    const actualRevenue = value("q3_actual");
    if (rawValue("q3_unknown") === "1") {
      baseline.push({ id: "q3", score: -1, unknown: true, text: "Вы не можете сопоставить плановую и фактическую траекторию выручки." });
    } else if (expectedRevenue !== null && actualRevenue !== null) {
      const gap = actualRevenue - expectedRevenue;
      baseline.push({ id: "q3", score: gap >= -5 ? 0 : gap >= -10 ? 1 : gap >= -20 ? 2 : 3, unknown: false, text: `К 31 августа по плану должно было быть ${expectedRevenue}%, фактически выполнено ${actualRevenue}%.` });
    }
    const sortAnswers = (answers) => [...answers].sort((a, b) => profileKey === "insufficient"
      ? Number(b.unknown) - Number(a.unknown) || b.score - a.score
      : b.score - a.score || Number(a.unknown) - Number(b.unknown));
    const meaningful = (answers) => profileKey === "no-critical" ? answers : answers.filter((item) => item.score > 0 || item.unknown);
    const preferredAnswer = (contour, answers) => {
      const type = resultType(contour.id);
      const byId = new Map(meaningful(answers).map((answer) => [answer.id, answer]));
      return evidencePriorityIds(contour.id, type).map((id) => byId.get(id)).find(Boolean)
        || sortAnswers(meaningful(answers))[0];
    };
    const selected = [preferredAnswer(primary, primaryAnswers), preferredAnswer(secondary, secondaryAnswers), sortAnswers(meaningful(baseline))[0]].filter(Boolean);
    const rest = sortAnswers(meaningful([...primaryAnswers, ...secondaryAnswers, ...baseline]));
    for (const item of rest) {
      if (selected.length >= 3) break;
      if (selected.some((selectedItem) => selectedItem.text === item.text)) continue;
      selected.push(item);
    }
    for (const item of sortAnswers([...primaryAnswers, ...secondaryAnswers, ...baseline])) {
      if (selected.length >= 3) break;
      if (selected.some((selectedItem) => selectedItem.text === item.text)) continue;
      selected.push(item);
    }
    return [...new Map(selected.map((item) => [item.text, item])).values()].slice(0, 3);
  }

