  function rawValue(name) {
    return new FormData(form).get(name);
  }

  function value(name) {
    const raw = rawValue(name);
    if (raw === null || raw === "" || raw === "unknown") return null;
    const number = Number(raw);
    return Number.isFinite(number) ? number : null;
  }

  function signal(percentValue) {
    if (percentValue <= 24) return { key: "low", label: "Сейчас спокойно" };
    if (percentValue <= 49) return { key: "moderate", label: "Есть отдельные сигналы" };
    if (percentValue <= 74) return { key: "strong", label: "Требует внимания" };
    return { key: "critical", label: "Начать отсюда" };
  }

  function validateQuestions(container) {
    let firstInvalid = null;
    for (const question of container.querySelectorAll(".diagnostic-question")) {
      const inputs = [...question.querySelectorAll("input")];
      const input = inputs[0];
      const valid = input.type === "radio"
        ? Boolean(question.querySelector("input:checked"))
        : inputs.every((field) => field.checkValidity());
      question.classList.toggle("is-invalid", !valid);
      if (!valid && !firstInvalid) firstInvalid = input;
    }
    if (!firstInvalid) {
      error.textContent = "";
      return true;
    }
    error.textContent = "Ответьте на все вопросы этого блока.";
    firstInvalid.focus();
    return false;
  }

